CREATE TABLE warehouse_ports (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 100,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT warehouse_port_name_check CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    CONSTRAINT warehouse_port_sort_order_check CHECK (sort_order BETWEEN 0 AND 100000)
);

CREATE UNIQUE INDEX warehouse_ports_name_unique_idx ON warehouse_ports(lower(name));
CREATE INDEX warehouse_ports_active_order_idx ON warehouse_ports(is_active, sort_order, lower(name));

